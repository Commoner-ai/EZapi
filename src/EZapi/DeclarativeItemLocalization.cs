using Il2Cpp;
using MelonLoader;
namespace EZapi;

/// <summary>
/// 已存在/读档物品在被显示或重新打开容器时刷新本地化。只触及已 Applied 的 JSON/DLL 物品；
/// 不枚举全局库存、不持有原生实例、不改玩家自定义名称、物品 ID、标签或存档。
/// </summary>
internal static class DeclarativeItemLocalization
{
    private static readonly NativeHookGroup Hooks=new("ezapi.items.localization");
    private static readonly HashSet<string> Logged=new(StringComparer.Ordinal);
    private static bool _refreshing;
    internal static void DirectoryReady()
    {
        if(!GameSession.OnThread)return;
        // NativeHookGroup checks the required signatures, native entries and patch
        // ownership. A regenerated wrapper DLL's whole-file hash is not a locale gate.
        Hooks.Install(typeof(DeclarativeItemLocalization),
            new(typeof(GameItem),nameof(GameItem.GetDisplayName),typeof(string),new[]{typeof(bool)},Prefix:nameof(BeforeDisplay)),
            // Native restoration can replace a container title with the compact item name.
            // Resolve the declared title after restoration so it survives reopening.
            new(typeof(GameItem),nameof(GameItem.RestoreContentWindowPosition),typeof(void),Type.EmptyTypes,Postfix:nameof(AfterRestore)));
    }
    private static void BeforeDisplay(GameItem __instance)
    {
        if(Hooks.Ready)Refresh(__instance);
    }
    private static void AfterRestore(GameItem __instance,bool __runOriginal)
    {
        if(Hooks.Ready&&__runOriginal)Refresh(__instance);
    }
    internal static void Refresh(GameItem? item)
    {
        if(_refreshing||!GameSession.OnThread||item is null||item.Pointer==IntPtr.Zero)return;
        try {
            _refreshing=true;
            RefreshItemText(item);
            MachineLayoutApi.RefreshLocalization(item);
        }catch(Exception error) {
            if(Logged.Count<500&&Logged.Add(error.GetType().Name+":"+error.Message))
                MelonLogger.Warning("[EZapi] EZAPI_ITEM_LOCALIZATION_REFRESH: "+error.GetType().Name+": "+error.Message);
        }finally{_refreshing=false;}
    }
    private static void RefreshItemText(GameItem item)
    {
            if(!ItemRegistry.TryGet(item.identifier,out var d))return;
            var locale=NativeItemLocalization.CurrentLocaleCode;
            if(d.LocalizedName is not null) {
                var old=item.name??"";
                var name=ItemText.Name(d,locale);
                // SetName writes the native custom-name slot too. Refresh only names previously
                // generated by this declaration; an arbitrary player rename is left untouched.
                if(ItemText.IsGeneratedName(d,old)) {
                    item.identifierName=name;
                    if(old!=name)item.SetName(name);
                }
            }
            if(d.DescriptionPlacement=="native") {
                if(ItemText.HasTranslation(d.LocalizedShortDescription??d.LocalizedDescription))item.shortDescription=ItemText.Resolve(d,d.LocalizedShortDescription??d.LocalizedDescription,d.ShortDescription??d.Description,locale);
                if(ItemText.HasTranslation(d.LocalizedLongDescription))item.longDescription=ItemText.Resolve(d,d.LocalizedLongDescription,d.LongDescription,locale);
                if(ItemText.HasTranslation(d.LocalizedFlavorText))item.flavorText=ItemText.Resolve(d,d.LocalizedFlavorText,d.FlavorText,locale);
                if(ItemText.HasTranslation(d.LocalizedCustomText))item.customText=ItemText.Resolve(d,d.LocalizedCustomText,d.CustomText,locale);
            }
            if(d.Container is {} box&&item.contentWindow is {} window) {
                if(box.LocalizedTitle is not null||box.Title is null&&d.LocalizedName is not null) {
                    var title=ItemText.Resolve(d,box.LocalizedTitle,box.Title??ItemText.Name(d,locale),locale);
                    if(!NativeWindowTitles.Matches(window,title))NativeWindowTitles.Set(window,title);
                }
            }
    }
    internal static NativeHookStatus Status()=>Hooks.Snapshot();
    internal static void Stop(){Hooks.Stop();Logged.Clear();NativeWindowTitles.Clear();_refreshing=false;}
}
